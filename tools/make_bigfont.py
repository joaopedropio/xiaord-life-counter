#!/usr/bin/env python3
"""Generate an anti-aliased 4-bit digit font header for the sketch.

usage: make_bigfont.py FONT.ttf NAME OUT.h (--xl | --l | --size PX) [--var STYLE]

  --xl     largest size whose digits are <= 76 px tall and where any 2 characters
           ("-9", "88"...) fit in 172 px  (life 0..99 and -1..-9)
  --l      largest size where any 4 characters ("-888") fit in 196 px (-999..999)
  --var    named instance of a variable font, e.g. Bold

Glyphs: 0-9, '-' and '+'. Each glyph is cropped to its ink box; 2 pixels/byte
(high nibble first), alpha 0..15. NAME prefixes the generated symbols
(NAME_GLYPHS, NAME_BITMAP, and the BigFont NAME). The header expects bigfont.h
to be included before it.
"""
import argparse
from PIL import Image, ImageDraw, ImageFont

CHARS = "0123456789-+"
DIGITS = "0123456789"
MAX_DIGIT_H = 76

ap = argparse.ArgumentParser()
ap.add_argument("ttf"); ap.add_argument("name"); ap.add_argument("out")
g = ap.add_mutually_exclusive_group(required=True)
g.add_argument("--xl", action="store_true"); g.add_argument("--l", action="store_true")
g.add_argument("--size", type=int)
ap.add_argument("--var")
args = ap.parse_args()


def load(size):
    f = ImageFont.truetype(args.ttf, size)
    if args.var:
        f.set_variation_by_name(args.var)
    return f


def ink(f, s):
    im = Image.new("L", (size_canvas(f), f.size * 2 + 20))
    ImageDraw.Draw(im).text((f.size, 10), s, font=f, fill=255)
    return im.getbbox() or (0, 0, 0, 0)


def size_canvas(f):
    return f.size * 8 + 40


def width(f, s):
    b = ink(f, s)
    return b[2] - b[0]


def fits(size):
    f = load(size)
    b = ink(f, DIGITS)
    if b[3] - b[1] > MAX_DIGIT_H:
        return False
    wide = max(DIGITS, key=lambda d: width(f, d))
    if args.xl:
        tests, limit = ["-" + wide, wide * 2, "-9", "20", "40"], 172
    else:
        tests, limit = ["-" + wide * 3, wide * 3], 196
    return all(width(f, s) <= limit for s in tests)


if args.size:
    size = args.size
else:
    size = 10
    while fits(size + 1):
        size += 1
font = load(size)

glyphs, data = [], bytearray()
for ch in CHARS:
    adv = round(font.getlength(ch))
    pad = size
    img = Image.new("L", (adv + 2 * pad, size * 2 + 20), 0)
    ImageDraw.Draw(img).text((pad, 10), ch, font=font, fill=255)
    box = img.getbbox()
    if not box:
        continue
    x0, y0, x1, y1 = box
    gimg = img.crop(box)
    w, h = gimg.size
    off = len(data)
    px = [round(v * 15 / 255) for v in gimg.getdata()]
    if len(px) % 2:
        px.append(0)
    for i in range(0, len(px), 2):
        data.append((px[i] << 4) | px[i + 1])
    glyphs.append((ch, off, w, h, x0 - pad, y0 - 10, adv))

top = min(gl[5] for gl in glyphs if gl[0].isdigit())
bot = max(gl[5] + gl[3] for gl in glyphs if gl[0].isdigit())
n = args.name
with open(args.out, "w") as f:
    f.write("// Generated by tools/make_bigfont.py from %s%s at %d px. Do not edit.\n"
            % (args.ttf.split('/')[-1], " (%s)" % args.var if args.var else "", size))
    f.write("#pragma once\n\n")
    f.write("const BigGlyph %s_GLYPHS[] = {\n" % n)
    for ch, off, w, h, dx, dy, adv in glyphs:
        f.write("  { '%s', %d, %d, %d, %d, %d, %d },\n" % (ch, off, w, h, dx, dy, adv))
    f.write("};\n")
    f.write("const uint8_t %s_BITMAP[%d] = {\n" % (n, len(data)))
    for i in range(0, len(data), 24):
        f.write("  " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ",\n")
    f.write("};\n")
    f.write("const BigFont %s = { %s_GLYPHS, %d, %s_BITMAP, %d, %d };\n"
            % (n, n, len(glyphs), n, top, bot - top))
print("%-32s %3d px  %6d bytes  digits %d px tall" % (args.out.split('/')[-1], size, len(data), bot - top))
